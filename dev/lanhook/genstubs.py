# Generates stubs.asm (ml64) + stubs.inc + dbghelp.def from dbghelp_exports.txt.
import re
lines=[l.strip().split(None,1) for l in open('dbghelp_exports.txt',newline='') if l.strip()]
named=[(int(o),n) for o,n in lines]
blank=[1101,1102,1103,1104,1105,1106,1107,1108,1109,1110,1115,1116,1117,1118,1119,1120]
have={o for o,_ in named}
blanks=[o for o in blank if o not in have]
allx=sorted([(o,n,False) for o,n in named]+[(o,'ord_%d'%o,True) for o in blanks])
HOOKED = {1219: 'Hook_SymFromAddr'}  # ordinal -> C hook fn in lanhook.c
NL = chr(10)
with open('stubs.asm','w',newline='') as f:
    f.write('; GENERATED by genstubs.py - do not edit.' + NL)
    f.write('.code' + NL + 'EXTERN g_Real:QWORD' + NL)
    for i,(o,n,_) in enumerate(allx):
        sym='x_'+n+'_stub'
        hook = HOOKED.get(o)
        if hook:
            f.write('EXTERN %s:PROC' % hook + NL)
            f.write('PUBLIC %s' % sym + NL + '%s PROC' % sym + NL + '  jmp %s' % hook + NL + '%s ENDP' % sym + NL)
        else:
            f.write('PUBLIC %s' % sym + NL + '%s PROC' % sym + NL + '  jmp qword ptr [g_Real + %d]' % (i*8) + NL + '%s ENDP' % sym + NL)
    f.write('END' + NL)
with open('stubs.inc','w',newline='') as f:
    f.write('/* GENERATED by genstubs.py - do not edit. */' + NL)
    f.write('#define DBG_NAMED %d' % len(named) + NL)
    f.write('static const struct { int ord; const char *name; } g_Exp[%d] = {' % len(allx) + NL)
    for o,n,isonly in allx:
        f.write('  {%d, %s},' % (o, 'NULL' if isonly else '"%s"' % n) + NL)
    f.write('};' + NL)
    f.write('#define DBG_TOTAL %d' % len(allx) + NL)
with open('dbghelp.def','w',newline='') as f:
    f.write('LIBRARY dbghelp' + NL + 'EXPORTS' + NL)
    for o,n,isonly in allx:
        sym='x_'+n+'_stub'
        if isonly: f.write('  %s @%d NONAME' % (sym,o) + NL)
        else: f.write('  %s=%s @%d' % (n,sym,o) + NL)
print('named=%d ordinal-only=%d total=%d' % (len(named), len(blanks), len(allx)))
print('wrote stubs.asm stubs.inc dbghelp.def')
